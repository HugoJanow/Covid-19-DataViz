// Fonction pour calculer les cas par million d'habitants
export const calculateCasesPerMillion = (cases, country) => {
  const population = POPULATION_DATA[country];
  if (!population || cases === 0) return 0;
  return Math.round((cases / population) * 1000000);
};

// Fonction pour obtenir la population d'un pays
export const getPopulation = (country) => {
  return POPULATION_DATA[country] || null;
};